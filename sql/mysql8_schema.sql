-- MySQL 8 schema starter. Import CSVs through MySQL Workbench Table Data Import Wizard.
-- Source columns intentionally retain readable names from the CSV dataset.
CREATE DATABASE IF NOT EXISTS auto_insurance_analytics;
USE auto_insurance_analytics;

CREATE TABLE IF NOT EXISTS telematics_claims (
  ClaimID VARCHAR(20) PRIMARY KEY,
  AccidentDate DATETIME NOT NULL,
  VehicleID VARCHAR(20) NOT NULL,
  Vehicle_Brand VARCHAR(50) NOT NULL,
  Model_Year SMALLINT NOT NULL,
  Speed_At_Impact_kmh DECIMAL(7,2) NOT NULL,
  G_Force_Impact DECIMAL(6,2) NOT NULL,
  Airbag_Deployed TINYINT NOT NULL,
  Braking_Duration_Seconds DECIMAL(6,2) NOT NULL,
  Impact_Point VARCHAR(20) NOT NULL,
  Weather_Condition VARCHAR(30) NOT NULL,
  Road_Type VARCHAR(40) NOT NULL,
  Crash_Area VARCHAR(40) NOT NULL,
  Vehicle_Latitude DECIMAL(10,6) NOT NULL,
  Vehicle_Longitude DECIMAL(10,6) NOT NULL,
  Actual_Repair_Cost_INR DECIMAL(12,2) NOT NULL,
  INDEX idx_claim_date (AccidentDate),
  INDEX idx_claim_brand (Vehicle_Brand),
  INDEX idx_vehicle (VehicleID)
);

CREATE TABLE IF NOT EXISTS partner_garages (
  GarageID VARCHAR(20) PRIMARY KEY,
  Garage_Name VARCHAR(120) NOT NULL,
  Area VARCHAR(40) NOT NULL,
  Latitude DECIMAL(10,6) NOT NULL,
  Longitude DECIMAL(10,6) NOT NULL,
  Brand_Specialization VARCHAR(50) NOT NULL,
  Parts_Available BOOLEAN NOT NULL,
  Preferred_Partner BOOLEAN NOT NULL,
  Daily_Service_Capacity INT NOT NULL,
  Avg_Repair_Turnaround_Days DECIMAL(6,2) NOT NULL,
  Labor_Rate_INR_Per_Hour DECIMAL(10,2) NOT NULL,
  INDEX idx_garage_brand_parts (Brand_Specialization, Parts_Available)
);

-- These downstream tables are generated by the Python pipeline; load their CSV exports to practice routing/model-result SQL.
CREATE TABLE IF NOT EXISTS garage_routing (
  ClaimID VARCHAR(20) PRIMARY KEY,
  Vehicle_Brand VARCHAR(50), Crash_Area VARCHAR(40), Recommended_GarageID VARCHAR(20),
  Recommended_Garage_Name VARCHAR(120), Recommended_Garage_Area VARCHAR(40),
  Recommended_Garage_Distance_km DECIMAL(10,3), Recommended_Garage_Travel_Minutes DECIMAL(10,2),
  Recommended_Garage_Turnaround_Days DECIMAL(8,2), Recommended_Garage_Est_Cycle_Hours DECIMAL(10,2),
  Recommended_Garage_Routing_Score DECIMAL(10,4), Nearest_Eligible_GarageID VARCHAR(20),
  Nearest_Eligible_Garage_Distance_km DECIMAL(10,3), Eligible_Garages_Considered INT,
  Preferred_Fallback_Used BOOLEAN, Candidate_Policy VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS holdout_predictions (
  ClaimID VARCHAR(20) PRIMARY KEY, AccidentDate DATETIME, Vehicle_Brand VARCHAR(50),
  Model_Year SMALLINT, Speed_At_Impact_kmh DECIMAL(7,2), G_Force_Impact DECIMAL(6,2),
  Airbag_Deployed TINYINT, Impact_Point VARCHAR(20), Actual_Repair_Cost_INR DECIMAL(12,2),
  Predicted_Repair_Cost_INR DECIMAL(12,2), Absolute_Error_INR DECIMAL(12,2), Signed_Error_INR DECIMAL(12,2)
);
